//! Precomputed fixed-base tables for edwards25519 `[k]B`.
//!
//! `ED25519_BASE_TABLE[i][j - 1]` is the point `[j * 16^i]B` for `i in 0..64`,
//! `j in 1..=8`, stored in affine **Niels** form
//! `[(y + x)_0..4, (y − x)_0..4, (2·d·x·y)_0..4]` — little-endian **51-bit**
//! limbs (the unsaturated 5×u64 representation of [`super::field::Fe`]) of
//! canonical plain residues, the three values the mixed addition
//! `Field::add_niels` consumes directly (7 multiplications, no conversion).
//! Only the magnitudes `1..=8` are stored: `Field::mul_base` recodes the
//! scalar into signed radix-16 digits in `[−8, 8)` and negates a gathered
//! entry by swapping its first two values and negating the third.
//!
//! `ED25519_BASE_2_256` is `[2^256]B` in the same form: the carry out of the
//! signed recoding of a 256-bit scalar is a 65th digit in `{0, 1}`, so every
//! 256-bit scalar is consumed exactly, with no reduction and no assumption
//! on its top bit.
//!
//! No entry is the identity (`j * 16^i` and `2^256` are never multiples of
//! the odd prime group order `L`), so the affine form is always valid.
//!
